import assert from "node:assert/strict";
import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";

import {
  compileFirefoxQueryStripping,
  firefoxQueryStrippingSource,
  renderFirefoxQueryStrippingModule,
  updateFirefoxQueryStripping
} from "../tools/rules/firefox-query-stripping.js";

const state = Object.freeze({
  data: Object.freeze([
    Object.freeze({
      id: "older",
      last_modified: 10,
      stripList: Object.freeze(["FBCLID", "shared"]),
      allowList: Object.freeze([])
    }),
    Object.freeze({
      id: "newer",
      last_modified: 20,
      stripList: Object.freeze(["gclid", "SHARED"]),
      allowList: Object.freeze(["Example.COM"])
    })
  ])
});

test("Firefox rule compiler is deterministic and preserves reviewable provenance", () => {
  const compiled = compileFirefoxQueryStripping(state);
  assert.equal(compiled.sourceUrl, firefoxQueryStrippingSource);
  assert.equal(compiled.recordsLastModified, 20);
  assert.deepEqual(compiled.records, [
    { id: "newer", lastModified: 20 },
    { id: "older", lastModified: 10 }
  ]);
  assert.deepEqual(compiled.stripParameters, ["gclid", "shared", "fbclid"]);
  assert.deepEqual(compiled.allowBaseDomains, ["example.com"]);

  const reversed = compileFirefoxQueryStripping({ data: [...state.data].reverse() });
  assert.equal(
    renderFirefoxQueryStrippingModule(reversed),
    renderFirefoxQueryStrippingModule(compiled)
  );
});

test("Firefox rule compiler rejects schema and domain drift", () => {
  assert.throws(
    () => compileFirefoxQueryStripping({}),
    /must contain a data array/u
  );
  assert.throws(
    () => compileFirefoxQueryStripping({ data: [{
      id: "broken",
      last_modified: 1,
      stripList: "fbclid",
      allowList: []
    }] }),
    /stripList must be an array of strings/u
  );
  assert.throws(
    () => compileFirefoxQueryStripping({ data: [{
      id: "broken",
      last_modified: 1,
      stripList: ["fbclid"],
      allowList: ["example.com/path"]
    }] }),
    /invalid domain/u
  );
});

test("Firefox rule updater writes atomically and check mode detects drift", async () => {
  const directory = await mkdtemp(join(tmpdir(), "min-ug-firefox-rules-"));
  const outputPath = join(directory, "firefox-query-stripping.ts");
  const fakeFetch = async (url: string) => ({
    ok: true,
    status: 200,
    url,
    text: async () => JSON.stringify(state)
  });

  const first = await updateFirefoxQueryStripping({ outputPath, fetchImplementation: fakeFetch });
  assert.equal(first.changed, true);
  const generated = await readFile(outputPath, "utf8");
  assert.match(generated, /Generated by tools\/update-firefox-query-stripping\.ts/u);

  const second = await updateFirefoxQueryStripping({ outputPath, fetchImplementation: fakeFetch });
  assert.equal(second.changed, false);
  await updateFirefoxQueryStripping({ outputPath, check: true, fetchImplementation: fakeFetch });

  await writeFile(outputPath, `${generated}\n`);
  await assert.rejects(
    updateFirefoxQueryStripping({ outputPath, check: true, fetchImplementation: fakeFetch }),
    /artifact is out of date/u
  );
});
